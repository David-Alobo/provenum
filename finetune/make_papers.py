def _chat(prompt: str, schema: dict, model: str, host: str, temperature: float) -> dict:
    """
    One chat call to Ollama with a JSON schema for the reply.

    Args:
        prompt (str): User message.
        schema (dict): JSON schema for the reply.
        model (str): Ollama model name.
        host (str): Ollama base URL.
        temperature (float): Sampling temperature (diversity of the generated text).

    Returns:
        dict: The parsed reply.
    """
    body = {"model": model, "messages": [{"role": "user", "content": prompt}], "format": schema,
            "stream": False, "options": {"temperature": temperature}, "think": False}  # fmt: skip
    request = urllib.request.Request(f"{host.rstrip('/')}/api/chat",
                                     data=json.dumps(body).encode(),
                                     headers={"Content-Type": "application/json"})  # fmt: skip
    with urllib.request.urlopen(request, timeout=600) as response:
        return json.loads(json.loads(response.read())["message"]["content"])


def _clean_vocab(vocab: dict) -> dict:
    """
    Check the model's vocabulary and make ids usable as path parts.

    Args:
        vocab (dict): Reply to VOCAB_PROMPT.

    Returns:
        dict: The same vocabulary with valid, unique snake_case ids.

    Raises:
        ValueError: If a list is too short or an id cannot be repaired.
    """

    def fix(term: dict, seen: set) -> dict:
        """
        Repair one id and make it unique.

        Args:
            term (dict): {id, phrase}.
            seen (set): Ids already used in the same list.

        Returns:
            dict: The term with a valid id.
        """
        tid = re.sub(r"[^a-z0-9_]+", "_", term["id"].lower()).strip("_")[:30] or "x"
        if not tid[0].isalpha():
            tid = "x" + tid
        while tid in seen:
            tid += "_b"
        seen.add(tid)
        return {"id": tid, "phrase": term["phrase"].strip()}

    for factor, low in (("entity", 2), ("condition", 3)):
        vals = vocab[factor]["values"]
        if len(vals) < low:
            raise ValueError(f"too few {factor} values")
        seen: set = set()
        vocab[factor]["values"] = [fix(v, seen) for v in vals[:6]]
        name = re.sub(r"[^a-z0-9_]+", "_", vocab[factor]["name"].lower()).strip("_")
        vocab[factor]["name"] = name if SNAKE.match(name) else factor
    reserved = {"metric", "subgroup", "outcome", "term", "n"}
    for factor in ("entity", "condition"):
        if vocab[factor]["name"] in reserved:
            vocab[factor]["name"] += "_" + factor
    if vocab["entity"]["name"] == vocab["condition"]["name"]:
        vocab["condition"]["name"] += "_arm"
    for key, low in (("metrics", 1), ("predictors", 2), ("subgroups", 2)):
        if len(vocab[key]) < low:
            raise ValueError(f"too few {key}")
        seen = set()
        vocab[key] = [fix(t, seen) for t in vocab[key][:4]]
    vocab["measure"]["id"] = fix(vocab["measure"], set())["id"]
    vocab["settings"] = [s for s in vocab["settings"] if re.search(r"\d\.\d", s)][:3]
    return vocab


def _wilson(k: int, n: int) -> tuple[float, float]:
    """
    Wilson 95% interval for a proportion.

    Args:
        k (int): Successes.
        n (int): Trials.

    Returns:
        tuple[float, float]: Lower and upper bound.
    """
    z, p = 1.959964, k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, centre - half), min(1.0, centre + half)


def _p_from_z(z: float) -> float:
    """
    Two-sided p-value for a standard normal statistic.

    Args:
        z (float): Test statistic.

    Returns:
        float: p-value, floored at 1e-12.
    """
    return max(1e-12, math.erfc(abs(z) / math.sqrt(2)))


def build_tables(vocab: dict, rng: random.Random) -> dict:
    """
    Generate consistent result tables for a vocabulary.

    Rates come from simulated counts; comparisons are paired differences against the reference
    arm computed from the same counts; p-values follow from the differences, with Holm-style
    adjustment within each entity and metric.

    Args:
        vocab (dict): Cleaned vocabulary.
        rng (random.Random): Random source.

    Returns:
        dict: {"tables": {name: {"keys": [...], "rows": [...], "formats": {...},
            "default": str, "hidden": bool}}, "names": {...}} with the chosen names.
    """
    ent, cond = vocab["entity"], vocab["condition"]
    ref = cond["values"][0]["id"]
    n = rng.choice([48, 96, 120, 200, 250, 312, 428, 600, 1024])
    pct = rng.choice(["pct1", "pct1", "pct1", "pct0", "pct2"])
    lo, hi = rng.choice(CI)
    dname, dlo, dhi = rng.choice(DELTA)
    p_raw, p_adj = rng.choice(PVALS)
    dec = rng.choice(["f1", "f2", "sig3"])
    names = {"rates": rng.choice(RATE_TABLES), "compare": rng.choice(COMPARE_TABLES),
             "measures": rng.choice(MEASURE_TABLES), "effects": rng.choice(EFFECT_TABLES),
             "hidden": rng.choice(HIDDEN_TABLES)}  # fmt: skip
    tables = {}

    # Rates: one row per entity and condition; columns per metric with interval bounds.
    counts, rows = {}, []
    for e in ent["values"]:
        base = {m["id"]: rng.uniform(0.15, 0.85) for m in vocab["metrics"]}
        for c in cond["values"]:
            shift = 0 if c["id"] == ref else rng.gauss(0, 0.07)
            row = {ent["name"]: e["id"], cond["name"]: c["id"]}
            for m in vocab["metrics"]:
                k = round(n * min(0.97, max(0.03, base[m["id"]] + shift)))
                counts[e["id"], c["id"], m["id"]] = k
                low, high = _wilson(k, n)
                row[m["id"]], row[m["id"] + lo], row[m["id"] + hi] = k / n, low, high
            row["n"] = n
            rows.append(row)
    tables[names["rates"]] = {"keys": [ent["name"], cond["name"]], "rows": rows, "hidden": False,
                              "default": pct, "formats": {"n": "int"}}  # fmt: skip

    # Paired comparisons against the reference arm.
    rows = []
    for e in ent["values"]:
        for m in vocab["metrics"]:
            group = []
            for c in cond["values"][1:]:
                k0, k1 = counts[e["id"], ref, m["id"]], counts[e["id"], c["id"], m["id"]]
                gained = max(0, k1 - k0) + rng.randint(3, 25)
                lost = gained - (k1 - k0)
                d = (k1 - k0) / n
                se = math.sqrt(max(gained + lost, 1)) / n
                group.append({ent["name"]: e["id"], "metric": m["id"], cond["name"]: c["id"],
                              dname: 100 * d, dlo: 100 * (d - 1.96 * se),
                              dhi: 100 * (d + 1.96 * se), "gained": gained, "lost": lost,
                              p_raw: _p_from_z(d / se)})  # fmt: skip
            ordered = sorted(group, key=lambda r: r[p_raw])
            for i, r in enumerate(ordered):
                r[p_adj] = min(1.0, max(r[p_raw] * (len(group) - i), ordered[i - 1][p_adj]
                                        if i else 0))  # fmt: skip
            rows += group
    tables[names["compare"]] = {
        "keys": [ent["name"], "metric", cond["name"]], "rows": rows, "hidden": False,
        "default": "f1", "formats": {dname: "+f1", "gained": "int", "lost": "int",
                                     p_raw: "p", p_adj: "p"}}  # fmt: skip

    # Continuous measurements.
    _meas, rows = vocab["measure"]["id"], []
    scale = 10 ** rng.uniform(-1, 3)
    for e in ent["values"]:
        mu = scale * rng.uniform(0.5, 2)
        for c in cond["values"]:
            m = mu * (1 + (0 if c["id"] == ref else rng.gauss(0, 0.15)))
            rows.append({ent["name"]: e["id"], cond["name"]: c["id"], "mean": m,
                         "sd": abs(m) * rng.uniform(0.1, 0.5),
                         "median": m * rng.uniform(0.9, 1.05)})  # fmt: skip
    tables[names["measures"]] = {"keys": [ent["name"], cond["name"]], "rows": rows,
                                 "hidden": False, "default": dec, "formats": {}}  # fmt: skip

    # Regression effects, one model per metric.
    rows = []
    for m in vocab["metrics"]:
        for t in vocab["predictors"]:
            est = rng.gauss(0, 0.6)
            se = rng.uniform(0.05, 0.3)
            rows.append({"outcome": m["id"], "term": t["id"], "estimate": est,
                         "ci_low": est - 1.96 * se, "ci_high": est + 1.96 * se,
                         "p": _p_from_z(est / se)})  # fmt: skip
    tables[names["effects"]] = {"keys": ["outcome", "term"], "rows": rows, "hidden": False,
                                "default": "f2", "formats": {"p": "p"}}  # fmt: skip

    # A secondary analysis the spec does not expose.
    rows = []
    for e in ent["values"]:
        for g in vocab["subgroups"]:
            for c in cond["values"][:2]:
                r = min(0.97, max(0.03, counts[e["id"], c["id"], vocab["metrics"][0]["id"]] / n
                                  + rng.gauss(0, 0.06)))  # fmt: skip
                rows.append({ent["name"]: e["id"], "subgroup": g["id"], cond["name"]: c["id"],
                             "rate": r, "n": rng.randint(20, max(21, n // 2))})  # fmt: skip
    tables[names["hidden"]] = {"keys": [ent["name"], "subgroup", cond["name"]], "rows": rows,
                               "hidden": True, "default": pct, "formats": {"n": "int"}}  # fmt: skip

    # Sometimes drop a visible table, so catalogues differ in size.
    if rng.random() < 0.3:
        tables.pop(rng.choice([names["measures"], names["effects"]]))
    return {"tables": tables, "names": names, "cols": {"lo": lo, "hi": hi, "d": dname,
            "dlo": dlo, "dhi": dhi, "p": p_raw, "padj": p_adj}}  # fmt: skip


def _shown(value: float, how: str) -> str:
    """
    The text a reader sees for a formatted value.

    Args:
        value (float): Raw value.
        how (str): provenum format.

    Returns:
        str: e.g. "46.3", "-2.1", "4.1 \\times 10^{-4}".
    """
    text = fmt(value, how)
    text = text.replace(r"\ensuremath{-}", "-")
    return re.sub(r"^\\ensuremath\{(.*)\}$", r"\1", text)


def _canonical(shown: str) -> str:
    """
    provenum's canonical form of a shown number.

    Args:
        shown (str): e.g. "4.1 \\times 10^{-4}" or "+6.8".

    Returns:
        str: e.g. "4.1e-4" or "6.8".
    """
    m = re.match(r"\s*([-+]?\d+(?:\.\d+)?)\s*\\times\s*10\^\{(-?\d+)\}", shown)
    return f"{m.group(1)}e{m.group(2)}" if m else shown.lstrip("+")


def _cell(tables: dict, table: str, key: dict, column: str) -> dict:
    """
    One fact: the path, shown text and gold of a table cell.

    Args:
        tables (dict): From `build_tables`.
        table (str): Table name.
        key (dict): Key column -> value identifying the row.
        column (str): Column name.

    Returns:
        dict: {path, value, shown, gold, hidden}.
    """
    t = tables[table]
    row = next(r for r in t["rows"] if all(r[k] == v for k, v in key.items()))
    path = "/".join([table] + [row[k] for k in t["keys"]] + [column])
    how = t["formats"].get(column, t["default"])
    shown = _shown(row[column], how)
    # What the wording needs to get right, without the number itself (a model shown the value
    # writes it out instead of the placeholder).
    if how == "p":
        hint = "below 0.05" if row[column] < 0.05 else "not below 0.05"
    elif how.startswith("+") or column.startswith(("estimate", "delta", "diff", "change")):
        hint = "positive" if row[column] > 0 else "negative"
    else:
        hint = ""
    return {"path": path, "shown": shown, "gold": None if t["hidden"] else path,
            "hidden": t["hidden"], "hint": hint}  # fmt: skip


def stories(vocab: dict, built: dict, rng: random.Random) -> list[list[tuple[dict, str]]]:
    """
    Choose the facts for each paragraph, with a description the writer model sees.

    Args:
        vocab (dict): Cleaned vocabulary.
        built (dict): From `build_tables`.
        rng (random.Random): Random source.

    Returns:
        list[list[tuple[dict, str]]]: Per paragraph, (fact, description) pairs.
    """
    T, nm, col = built["tables"], built["names"], built["cols"]
    ent, cond = vocab["entity"], vocab["condition"]
    E, C = ent["name"], cond["name"]
    ph = {t["id"]: t["phrase"] for k in ("metrics", "predictors", "subgroups")
          for t in vocab[k]}  # fmt: skip
    ph.update({v["id"]: v["phrase"] for f in (ent, cond) for v in f["values"]})
    ref = cond["values"][0]
    out = []

    def compare() -> list[tuple[dict, str]]:
        """
        A paired comparison of one arm with the reference.

        Returns:
            list[tuple[dict, str]]: Facts and descriptions.
        """
        e, c = rng.choice(ent["values"]), rng.choice(cond["values"][1:])
        m = rng.choice(vocab["metrics"])
        where = f"{ph[m['id']]} rate for {e['phrase']}"
        facts = [(_cell(T, nm["rates"], {E: e["id"], C: ref["id"]}, m["id"]),
                  f"{where} under {ref['phrase']} (reference), in %"),
                 (_cell(T, nm["rates"], {E: e["id"], C: c["id"]}, m["id"]),
                  f"{where} under {c['phrase']}, in %")]  # fmt: skip
        if rng.random() < 0.6:
            facts += [(_cell(T, nm["rates"], {E: e["id"], C: c["id"]}, m["id"] + col[s]),
                       f"{b} bound of the 95% interval of that {c['phrase']} rate")
                      for s, b in (("lo", "lower"), ("hi", "upper"))]  # fmt: skip
        key = {E: e["id"], "metric": m["id"], C: c["id"]}
        facts.append((_cell(T, nm["compare"], key, col["d"]),
                       (f"change in {ph[m['id']]} rate, {c['phrase']} minus {ref['phrase']}, "
                       f"for {e['phrase']}, in percentage points (sign shown)")))  # fmt: skip
        if rng.random() < 0.5:
            facts += [(_cell(T, nm["compare"], key, col[s]), f"{b} bound of that change's interval")
                      for s, b in (("dlo", "lower"), ("dhi", "upper"))]  # fmt: skip
        if rng.random() < 0.4:
            facts += [(_cell(T, nm["compare"], key, c), f"number of {e['phrase']} cases that "
                       f"{c_} with {c['phrase']} relative to {ref['phrase']} (a count)")
                      for c, c_ in (("gained", "succeeded only"), ("lost", "failed only"))]  # fmt: skip
        pcol = rng.choice(["p", "padj"])
        facts.append((_cell(T, nm["compare"], key, col[pcol]),
                      "p-value of that change" + (" (multiplicity-adjusted)" if pcol == "padj"
                                                  else "")))  # fmt: skip
        return facts

    def overview() -> list[tuple[dict, str]]:
        """
        One metric across several entities under one arm.

        Returns:
            list[tuple[dict, str]]: Facts and descriptions.
        """
        m, c = rng.choice(vocab["metrics"]), rng.choice(cond["values"])
        es = rng.sample(ent["values"], k=min(len(ent["values"]), rng.randint(2, 4)))
        return [
            (
                _cell(T, nm["rates"], {E: e["id"], C: c["id"]}, m["id"]),
                f"{ph[m['id']]} rate for {e['phrase']} under {c['phrase']}, in %",
            )
            for e in es
        ]

    def measures() -> list[tuple[dict, str]]:
        """
        Mean and spread of the continuous measure for one entity across arms.

        Returns:
            list[tuple[dict, str]]: Facts and descriptions.
        """
        e = rng.choice(ent["values"])
        cs = rng.sample(cond["values"], k=min(len(cond["values"]), rng.randint(2, 3)))
        facts = []
        for c in cs:
            for column in rng.choice([["mean", "sd"], ["mean"], ["median"]]):
                facts.append((_cell(T, nm["measures"], {E: e["id"], C: c["id"]}, column),
                              (f"{column} {vocab['measure']['phrase']} for {e['phrase']} under "
                              f"{c['phrase']}, in {vocab['measure']['unit']}")))  # fmt: skip
        return facts

    def effects() -> list[tuple[dict, str]]:
        """
        Regression estimates with intervals.

        Returns:
            list[tuple[dict, str]]: Facts and descriptions.
        """
        m = rng.choice(vocab["metrics"])
        facts = []
        for t in rng.sample(vocab["predictors"], k=min(2, len(vocab["predictors"]))):
            key = {"outcome": m["id"], "term": t["id"]}
            facts.append(
                (
                    _cell(T, nm["effects"], key, "estimate"),
                    f"regression estimate (log-odds) of {ph[t['id']]} on {ph[m['id']]}",
                )
            )
            if rng.random() < 0.6:
                facts += [(_cell(T, nm["effects"], key, c), f"{b} bound of that estimate")
                          for c, b in (("ci_low", "lower"), ("ci_high", "upper"))]  # fmt: skip
            if rng.random() < 0.5:
                facts.append((_cell(T, nm["effects"], key, "p"), "p-value of that estimate"))
        return facts

    def subgroup() -> list[tuple[dict, str]]:
        """
        A secondary analysis from the table the catalogue does not show.

        Returns:
            list[tuple[dict, str]]: Facts and descriptions.
        """
        e, g = rng.choice(ent["values"]), rng.choice(vocab["subgroups"])
        c = cond["values"][rng.randint(0, 1)]
        m = vocab["metrics"][0]
        facts = [(_cell(T, nm["hidden"], {E: e["id"], "subgroup": g["id"], C: c["id"]}, "rate"),
                  (f"{ph[m['id']]} rate in the {g['phrase']} subgroup of {e['phrase']} under "
                  f"{c['phrase']} (secondary analysis), in %"))]  # fmt: skip
        if rng.random() < 0.5:
            facts.append(
                (
                    _cell(T, nm["rates"], {E: e["id"], C: c["id"]}, m["id"]),
                    f"{ph[m['id']]} rate for all of {e['phrase']} under {c['phrase']}, in %",
                )
            )
        return facts

    kinds = [compare, compare, overview, subgroup]
    kinds += [measures] if nm["measures"] in T else []
    kinds += [effects] if nm["effects"] in T else []
    for _ in range(rng.randint(3, 6)):
        facts = rng.choice(kinds)()
        if rng.random() < 0.3:
            facts += rng.choice(kinds)()
        seen, unique = set(), []
        for f, d in facts:
            if f["path"] not in seen:
                seen.add(f["path"])
                unique.append((f, d))
        out.append(unique[:9])
    return out


def write_paragraph(study: str, unit: str, facts: list[tuple[dict, str]], setting: str | None,
                    model: str, host: str, rng: random.Random
                    ) -> tuple[str | None, list[dict]]:  # fmt: skip
    """
    Ask the model for a paragraph with placeholders and check it.

    Args:
        study (str): One-sentence study description.
        unit (str): Unit of the continuous measure.
        facts (list[tuple[dict, str]]): Facts and descriptions.
        setting (str | None): A setting phrase to include verbatim, or None.
        model (str): Ollama model.
        host (str): Ollama URL.
        rng (random.Random): Random source (temperature).

    Returns:
        tuple[str | None, list[dict]]: Paragraph with {{k}} placeholders (None after three
            failed attempts) and the rejected attempts with the reason.
    """
    listing = "\n".join(f"{{{{{k}}}}}: {d} (shown as {f['shown']})"
                        for k, (f, d) in enumerate(facts, 1))  # fmt: skip
    extra = f'Also state this protocol setting word for word: "{setting}".' if setting else ""
    prompt = WRITE_PROMPT.format(study=study, unit=unit, extra=extra, facts=listing)
    schema = {"type": "object", "properties": {"paragraph": {"type": "string"}},
              "required": ["paragraph"]}  # fmt: skip
    failures = []
    for _ in range(3):
        text = _chat(prompt, schema, model, host, rng.uniform(0.6, 1.0))["paragraph"]
        counts = {k: text.count(f"{{{{{k}}}}}") for k in range(1, len(facts) + 1)}
        stray = re.search(r"\d\.\d", re.sub(r"\{\{\d+\}\}", "", text.replace(setting or "\0", "")))
        if any(c != 1 for c in counts.values()):
            reason = f"placeholder counts {counts}"
        elif stray:
            reason = f"number written out: {stray.group()}"
        elif setting and setting not in text:
            reason = "setting not verbatim"
        else:
            return text, failures
        failures.append({"reason": reason, "text": text})
    return None, failures


def _latex(text: str) -> str:
    """
    Escape the characters a model writes in prose that LaTeX treats specially.

    Args:
        text (str): Plain paragraph.

    Returns:
        str: LaTeX-safe paragraph.
    """
    return text.replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")


def _sentence(text: str, start: int) -> str:
    """
    The sentence around a position (same rule as provenum's gold items).

    Args:
        text (str): Paragraph.
        start (int): Position of the marked number.

    Returns:
        str: The sentence.
    """
    s0 = text.rfind(". ", 0, start)
    s0 = s0 + 2 if s0 >= 0 else 0
    s1 = text.find(". ", start)
    return text[s0 : s1 + 1 if s1 > 0 else len(text)]


def _fill(text: str, facts: list[dict], mark: int | None, latex: bool = False) -> str:
    """
    Replace placeholders with the numbers, marking one of them or writing `\\val{}`.

    Args:
        text (str): Paragraph with {{k}} placeholders (1-based).
        facts (list[dict]): Facts in placeholder order.
        mark (int | None): Placeholder to mark with [[...]], or None.
        latex (bool): Write `\\val{path}` for catalogued facts (the results.tex form).

    Returns:
        str: The filled paragraph.
    """

    def one(m: re.Match) -> str:
        """
        Text for one placeholder.

        Args:
            m (re.Match): Placeholder match.

        Returns:
            str: Shown number, marked number or `\\val{}` call.
        """
        k = int(m.group(1))
        f = facts[k - 1]
        if latex and not f["hidden"]:
            return rf"\val{{{f['path']}}}"
        return f"[[{f['shown']}]]" if k == mark else f["shown"]

    return re.sub(r"\{\{(\d+)\}\}", one, text)


def paper_items(paragraphs: list[tuple[str, list[dict], str | None]]) -> tuple[list[dict], str]:
    """
    Turn written paragraphs into gold items and a LaTeX results section.

    Args:
        paragraphs (list[tuple[str, list[dict], str | None]]): (text with placeholders, facts,
            setting phrase or None) per paragraph.

    Returns:
        tuple[list[dict], str]: Items and the results.tex text.
    """
    items, tex = [], []
    for text, facts, setting in paragraphs:
        text = _latex(" ".join(text.split()))
        setting_tex = _latex(setting) if setting else None
        plain = _fill(text, facts, None)
        for k, f in enumerate(facts, 1):
            marked = _fill(text, facts, k)
            items.append({"number": _canonical(f["shown"]), "written": f["shown"],
                          "sentence": _sentence(marked, marked.find("[[")),
                          "paragraph": plain[:1200], "gold": f["gold"],
                          "hidden": f["hidden"]})  # fmt: skip
        if setting_tex and setting_tex in plain:
            num = re.search(r"\d+\.\d+", setting_tex).group()
            pos = plain.find(setting_tex)
            marked = (
                plain[:pos]
                + setting_tex.replace(num, f"[[{num}]]", 1)
                + plain[pos + len(setting_tex) :]
            )
            items.append({"number": num, "written": num,
                          "sentence": _sentence(marked, marked.find("[[")),
                          "paragraph": plain[:1200], "gold": None, "hidden": False,
                          "setting": True})  # fmt: skip
        tex.append(_fill(text, facts, None, latex=True))
    for i, it in enumerate(items):
        it["id"] = i
    return items, "\n\n".join(tex) + "\n"


def notes_for(vocab: dict, built: dict, rng: random.Random) -> str:
    """
    Project notes as an author might write them (sometimes none, sometimes partial).

    Args:
        vocab (dict): Cleaned vocabulary.
        built (dict): From `build_tables`.
        rng (random.Random): Random source.

    Returns:
        str: Notes text (may be empty).
    """
    if rng.random() < 0.25:
        return ""
    ent, cond = vocab["entity"], vocab["condition"]
    lines = [vocab["study"]]
    lines.append(
        f"{ent['name']}: " + ", ".join(f"{v['id']} ({v['phrase']})" for v in ent["values"])
    )
    lines.append(f"{cond['name']}: " + ", ".join(f"{v['id']} ({v['phrase']})" for v in cond["values"])
                 + f"; {cond['values'][0]['id']} is the reference.")  # fmt: skip
    if rng.random() < 0.7:
        lines.append(
            "metrics: " + ", ".join(f"{m['id']} ({m['phrase']})" for m in vocab["metrics"])
        )
    if rng.random() < 0.5:
        c = built["cols"]
        lines.append(f"{built['names']['compare']} holds changes against the reference in points "
                     f"({c['d']}, interval {c['dlo']}/{c['dhi']}) and p-values ({c['p']}, "
                     f"adjusted {c['padj']}).")  # fmt: skip
    if rng.random() < 0.5:
        lines.append("Secondary and subgroup analyses are not in the catalogue: answer null.")
    return "\n".join(lines)


def make_paper(pid: str, field: str, out: Path, model: str, host: str, seed: int) -> dict:
    """
    Generate one synthetic paper and write its files.

    Args:
        pid (str): Paper id (directory name).
        field (str): Field of study.
        out (Path): Output root.
        model (str): Ollama model.
        host (str): Ollama URL.
        seed (int): Random seed.

    Returns:
        dict: Summary {id, field, items, paragraphs, dropped}.
    """
    rng = random.Random(seed)
    vocab = _clean_vocab(_chat(VOCAB_PROMPT.format(field=field), VOCAB_SCHEMA, model, host,
                               rng.uniform(0.7, 1.0)))  # fmt: skip
    built = build_tables(vocab, rng)
    written, dropped, rejected = [], 0, []
    for facts in stories(vocab, built, rng):
        setting = (
            rng.choice(vocab["settings"]) if vocab["settings"] and rng.random() < 0.25 else None
        )
        text, failures = write_paragraph(vocab["study"], vocab["measure"]["unit"], facts,
                                         setting, model, host, rng)  # fmt: skip
        rejected += failures
        if text is None:
            dropped += 1
            continue
        written.append((text, [f for f, _ in facts], setting))
    items, tex = paper_items(written)

    d = out / pid
    (d / "tables").mkdir(parents=True, exist_ok=True)
    spec = []
    for name, t in built["tables"].items():
        cols = list(t["rows"][0])
        with open(d / "tables" / f"{name}.csv", "w", newline="", encoding="utf-8") as handle:
            w = csv.DictWriter(handle, fieldnames=cols)
            w.writeheader()
            w.writerows(t["rows"])
        if not t["hidden"]:
            fm = ", ".join(f'{k} = "{v}"' for k, v in t["formats"].items())
            spec.append(f'[[table]]\nfile = "{name}.csv"\nkeys = {json.dumps(t["keys"])}\n'
                        f'default = "{t["default"]}"\nformats = {{ {fm} }}\n')  # fmt: skip
    (d / "spec.toml").write_text("\n".join(spec), encoding="utf-8")
    (d / "notes.txt").write_text(notes_for(vocab, built, rng), encoding="utf-8")
    (d / "results.tex").write_text(tex, encoding="utf-8")
    (d / "items.json").write_text(json.dumps(items, indent=1, ensure_ascii=False), encoding="utf-8")
    meta = {"id": pid, "field": field, "seed": seed, "model": model, "vocab": vocab,
            "names": built["names"], "paragraphs": len(written), "dropped": dropped,
            "items": len(items), "rejected": rejected}  # fmt: skip
    (d / "meta.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False), encoding="utf-8")
    return {k: meta[k] for k in ("id", "field", "items", "paragraphs", "dropped")}


def main() -> None:
    """Generate papers in parallel, skipping ones already written (resumable)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--n", type=int, default=300, help="training papers")
    parser.add_argument("--n-test", type=int, default=40, help="papers from held-out fields")
    parser.add_argument("--host", default="http://127.0.0.1:11434")
    parser.add_argument("--model", default="qwen3:32b")
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()

    jobs = [(f"train{i:04d}", TRAIN_FIELDS[i % len(TRAIN_FIELDS)], 1000 + i) for i in range(args.n)]
    jobs += [
        (f"test{i:04d}", TEST_FIELDS[i % len(TEST_FIELDS)], 9000 + i) for i in range(args.n_test)
    ]
    jobs = [j for j in jobs if not (args.out / j[0] / "meta.json").exists()]
    print(f"{len(jobs)} papers to generate", flush=True)
    with ThreadPoolExecutor(args.workers) as pool:
        futures = {pool.submit(make_paper, pid, field, args.out, args.model, args.host, seed): pid
                   for pid, field, seed in jobs}  # fmt: skip
        for done, future in enumerate(as_completed(futures), 1):
            try:
                print(done, future.result(), flush=True)
            except Exception:  # noqa: BLE001 - one bad paper must not stop the run
                print(done, futures[future], "FAILED", traceback.format_exc(limit=2), flush=True)


if __name__ == "__main__":
    main()
