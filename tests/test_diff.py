import shutil
import subprocess

import pytest

from provenum.cli import main
from provenum.diff import compare, number, read_values, report, uses

OLD = r"""% Generated by provenum
\provenumset{summary/vina/base/top1}{46.3}
\provenumset{summary/vina/box2/top1}{53.0}
\provenumset{cmp/vina/box2/delta_pts}{+6.8}
\provenumset{cmp/vina/box2/delta_low}{3.5}
\provenumset{cmp/vina/box2/delta_high}{10.0}
\provenumset{cmp/vina/box2/p_holm}{\ensuremath{4.1 \times 10^{-4}}}
\provenumset{cmp/vina/box6/delta_pts}{+1.2}
\provenumset{old/only}{1.0}
"""

NEW = r"""% Generated by provenum
\provenumset{summary/vina/base/top1}{46.3}
\provenumset{summary/vina/box2/top1}{47.9}
\provenumset{cmp/vina/box2/delta_pts}{+1.6}
\provenumset{cmp/vina/box2/delta_low}{\ensuremath{-}1.2}
\provenumset{cmp/vina/box2/delta_high}{4.4}
\provenumset{cmp/vina/box2/p_holm}{0.31}
\provenumset{cmp/vina/box6/delta_pts}{\ensuremath{-}0.4}
"""

PAPER = r"""Vina's top-1 success rose from \val{summary/vina/base/top1}\% to
\val{summary/vina/box2/top1}\% with the 2~\AA{} box (\val{cmp/vina/box2/delta_pts} points
[\val{cmp/vina/box2/delta_low}, \val{cmp/vina/box2/delta_high}]; Holm $p = \val{cmp/vina/box2/p_holm}$).
% A comment citing \val{cmp/vina/box6/delta_pts} is not a use.

The 6~\AA{} box changed it by \val{cmp/vina/box6/delta_pts} points. A removed value: \val{old/only}.
"""


def test_read_values_handles_nested_braces():
    v = read_values(OLD)
    assert v["cmp/vina/box2/p_holm"] == r"\ensuremath{4.1 \times 10^{-4}}"
    assert len(v) == 8


@pytest.mark.parametrize(
    "text, expected",
    [("+6.8", 6.8), (r"\ensuremath{-}1.2", -1.2), (r"\ensuremath{4.1 \times 10^{-4}}", 4.1e-4),
     ("0.31", 0.31), ("--", None), (None, None)],
)  # fmt: skip
def test_number(text, expected):
    assert number(text) == pytest.approx(expected) if expected is not None else number(text) is None


def test_compare_flags_claim_breaking_changes():
    changes = {c.path: c for c in compare(read_values(OLD), read_values(NEW))}
    assert "summary/vina/base/top1" not in changes  # unchanged
    assert changes["cmp/vina/box2/p_holm"].flags == ["now not below 0.05"]
    assert "interval now includes 0" in changes["cmp/vina/box2/delta_low"].flags
    assert "interval now includes 0" in changes["cmp/vina/box2/delta_high"].flags
    assert changes["cmp/vina/box6/delta_pts"].flags == ["sign changed"]
    assert changes["cmp/vina/box2/delta_pts"].flags == []  # smaller, same sign
    assert changes["old/only"].new is None


def test_report_shows_sentences_with_old_and_new(tmp_path):
    paper = tmp_path / "results.tex"
    paper.write_text(PAPER, encoding="utf-8")
    new = read_values(NEW)
    cited = uses([paper])
    assert len(cited["cmp/vina/box6/delta_pts"]) == 1  # the commented-out citation is ignored
    text = report(compare(read_values(OLD), new), cited, new)
    assert "[53.0 -> 47.9]%" in text
    assert "2 Å box" in text
    assert "sign changed" in text
    assert "removed: the text will show ??" in text
    assert f"{paper}:6  NEEDS A LOOK" in text  # line of the citation


def test_cli_strict_exit_code(tmp_path, capsys):
    (tmp_path / "old.tex").write_text(OLD, encoding="utf-8")
    (tmp_path / "numbers.tex").write_text(NEW, encoding="utf-8")
    (tmp_path / "results.tex").write_text(PAPER, encoding="utf-8")
    args = ["diff", str(tmp_path / "numbers.tex"), "--old", str(tmp_path / "old.tex"),
            "--manuscript", str(tmp_path / "results.tex")]  # fmt: skip
    assert main(args) == 0
    assert main([*args, "--strict"]) == 1
    assert main(["diff", str(tmp_path / "numbers.tex"), "--old", str(tmp_path / "numbers.tex"),
                 "--strict"]) == 0  # fmt: skip
    assert "0 cited value(s) changed" in capsys.readouterr().out


@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_cli_reads_old_values_from_git(tmp_path, capsys):
    def git(*a):
        subprocess.run(["git", *a], cwd=tmp_path, check=True, capture_output=True)

    git("init", "-q")
    values = tmp_path / "numbers.tex"
    values.write_text(OLD, encoding="utf-8")
    git("add", "numbers.tex")
    git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "old")
    values.write_text(NEW, encoding="utf-8")
    (tmp_path / "results.tex").write_text(PAPER, encoding="utf-8")
    code = main(["diff", str(values), "--manuscript", str(tmp_path / "results.tex"),
                 "--format", "markdown"])  # fmt: skip
    out = capsys.readouterr().out
    assert code == 0
    assert out.startswith("## provenum diff:")
    assert "**needs a look**" in out
    assert "sign changed" in out
