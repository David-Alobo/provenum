"""Prevention mode: generate LaTeX values from result tables, so prose numbers cannot drift.

`numbers.tex` defines one entry per table cell, addressed by path, e.g.
`\\val{summary/vina/box_padding_2/top1}` -> 53.0. The manuscript writes `\\val{...}` instead of
a hard-coded number; when an analysis is rerun and the tables regenerated, the text follows.
An unknown path prints a bold "??" and a LaTeX warning, so a broken reference is visible.
The optional argument, `\\val[>0]{...}`, is a guard checked by `provenum check`; LaTeX ignores it.
"""

import csv
import math
import re
import tomllib
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path

# A citation in the manuscript: group 1 is the optional guard, group 2 the path.
VAL = re.compile(r"\\val(?:\[([^\]]*)\])?\{([^{}]*)\}")

PREAMBLE = r"""% Generated by provenum from result tables. Do not edit: regenerate instead.
\makeatletter
\providecommand{\val}[2][]{\ifcsname provenum@#2\endcsname\csname provenum@#2\endcsname\else
  \textbf{??}\PackageWarning{provenum}{Undefined value #2}\fi}
\providecommand{\provenumset}[2]{\expandafter\def\csname provenum@#1\endcsname{#2}}
\makeatother
"""


@dataclass
class TableSpec:
    """How to address and format one CSV file."""

    file: str
    keys: list[str]  # columns whose values name the row, in path order
    formats: dict[str, str] = field(default_factory=dict)  # column -> format
    default: str = "auto"
    # One value per row (e.g. recorded.csv): the path is the keys alone, the value is this column
    # and, if format_column is set, each row names its own format.
    value_column: str | None = None
    format_column: str | None = None


def fmt(value: float, how: str, column: str = "") -> str:
    """
    Format a value for LaTeX.

    Formats: pct0/pct1/pct2 (proportion as percent), f0..f4 (fixed decimals), sig2/sig3
    (significant figures), p (two significant figures; scientific below 0.001), int, and a
    leading "+" (e.g. "+f1") to always show the sign. "auto" uses p for columns named p or
    p_*, pct1 for proportions in [0, 1], int for whole numbers, and sig3 otherwise.

    Args:
        value (float): Value to format.
        how (str): Format name.
        column (str): Column name, used by "auto".

    Returns:
        str: LaTeX-ready text (minus signs as $-$, scientific notation in math).
    """
    if not math.isfinite(value):
        return "--"
    if how == "auto":
        if column == "p" or column.startswith("p_"):
            how = "p"
        elif value == round(value) and abs(value) >= 1:
            how = "int"
        elif 0 <= value <= 1:
            how = "pct1"
        else:
            how = "sig3"
    signed = how.startswith("+")
    how = how.lstrip("+")
    if how.startswith("pct"):
        text = f"{100 * value:.{int(how[3:] or 1)}f}"
    elif how.startswith("f"):
        text = f"{value:.{int(how[1:])}f}"
    elif how == "int":
        text = f"{round(value):d}"
    elif how.startswith("sig"):
        text = f"{value:.{int(how[3:])}g}"
    elif how == "p":
        if value < 0.001:
            mant, exp = f"{value:.1e}".split("e")
            return rf"\ensuremath{{{mant} \times 10^{{{int(exp)}}}}}"
        text = f"{value:#.2g}".rstrip(
            "."
        )  # two significant figures, keeping a trailing zero (0.20)
    else:
        raise ValueError(f"Unknown format {how!r}")
    if text.startswith("-"):
        return rf"\ensuremath{{-}}{text[1:]}"  # works in text and inside $...$
    return f"+{text}" if signed and value > 0 else text


def load_specs(path: str | Path) -> list[TableSpec]:
    """
    Read table specs from TOML: [[table]] file, keys, default, formats, and optionally value and
    format (for one-value-per-row tables such as recorded.csv).

    Args:
        path (str | Path): Spec file.

    Returns:
        list[TableSpec]: One per table.
    """
    data = tomllib.loads(Path(path).read_text(encoding="utf-8"))
    return [TableSpec(t["file"], t["keys"], t.get("formats", {}), t.get("default", "auto"),
                      t.get("value"), t.get("format"))
            for t in data.get("table", [])]  # fmt: skip


def cells(spec: TableSpec, root: str | Path) -> Iterator[tuple[str, float, str]]:
    """
    Every numeric cell a spec exposes, with its path and format.

    Args:
        spec (TableSpec): One table.
        root (str | Path): Directory the spec's file path is relative to.

    Yields:
        tuple[str, float, str]: (path, value, format name).
    """
    prefix = re.sub(r"\.csv$", "", spec.file)
    with open(Path(root) / spec.file, newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            key = "/".join([prefix] + [row[k] for k in spec.keys])
            if spec.value_column:
                own = row.get(spec.format_column) if spec.format_column else None
                pairs = [(key, row[spec.value_column], own)]
            else:
                pairs = [(f"{key}/{c}", v, None) for c, v in row.items() if c not in spec.keys]
            for path, cell, how in pairs:
                try:
                    value = float(cell)
                except (TypeError, ValueError):
                    continue
                column = spec.value_column or path.rpartition("/")[2]
                yield path, value, how or spec.formats.get(column, spec.default)


def generate(specs: list[TableSpec], root: str | Path) -> tuple[str, int]:
    """
    Build numbers.tex content from the tables.

    Args:
        specs (list[TableSpec]): Which tables and how to format them.
        root (str | Path): Directory the spec's file paths are relative to.

    Returns:
        tuple[str, int]: The LaTeX text and the number of values defined.
    """
    lines, count = [PREAMBLE], 0
    for spec in specs:
        for path, value, how in cells(spec, root):
            text = fmt(value, how, spec.value_column or path.rpartition("/")[2])
            lines.append(rf"\provenumset{{{path}}}{{{text}}}")
            count += 1
    return "\n".join(lines) + "\n", count


# Numbers that are settings rather than results, e.g. "95% interval", "2,000 resamples".
SETTINGS = re.compile(
    r"^\s*(?:\\?%\s*(?:wilson|confidence|ci\b|bootstrap|interval|paired)|\s*(?:resamples|repetitions|folds|seeds?)\b)",
    re.IGNORECASE,
)


def lint(path: str | Path) -> list[tuple[int, str, str]]:
    """
    Flag hard-coded decimal numbers in prose (outside \\val{} and LaTeX tables).

    Integers are left alone (counts and design constants are usually fixed by the design),
    and so are numbers that read as settings.

    Args:
        path (str | Path): Manuscript file.

    Returns:
        list[tuple[int, str, str]]: (line, number, line text) for each hard-coded decimal.
    """
    from provenum.latex import _clean

    out, in_tab = [], False
    for n, raw in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        if "\\begin{tabular" in raw:
            in_tab = True
        if not in_tab:
            line = VAL.sub(" ", raw)
            line = _clean(line)
            for m in re.finditer(r"(?<![\w.\\])[-−]?\d+\.\d+(?![\w])", line):
                if SETTINGS.match(line[m.end() : m.end() + 30]):
                    continue
                out.append((n, m.group(), raw.strip()[:140]))
        if "\\end{tabular" in raw:
            in_tab = False
    return out
